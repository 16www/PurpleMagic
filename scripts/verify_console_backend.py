        page.get_by_role('button',name='查看literal_%!',exact=True).click()
        expect(page.get_by_role('dialog')).to_contain_text('未知')
        page.get_by_role('button',name='关闭',exact=True).click()
        page.get_by_label('查询范围').select_option('characters')
        page.get_by_label('查询账号或角色').fill('%')
        page.get_by_role('button',name='查询',exact=True).click()
        expect(page.locator('tbody tr')).to_have_count(1)
        expect(page.locator('tbody')).to_contain_text('literal_%!')
        page.screenshot(path=str(out/'roles-real-backend.png'),full_page=True)
        page.get_by_label('查询账号或角色').fill('0010')
        page.get_by_role('button',name='查询',exact=True).click()
        page.get_by_role('button',name='查看探险1-0',exact=True).click()
