        # its submit gesture. Delay it so this loading boundary is deterministic.
        page.evaluate('''() => { window.catalogOriginalFetch=window.fetch;
          window.fetch=(url,options)=>String(url).includes('/v1/quests?')
            ? window.catalogOriginalFetch(url,options).then(r=>new Promise(resolve=>setTimeout(()=>resolve(r),500)))
            : window.catalogOriginalFetch(url,options); }''')
