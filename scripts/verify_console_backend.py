        page.get_by_label('金币',exact=True).fill('29')
        page.get_by_role('button',name='预览邮件',exact=True).click()
        details=page.locator('[aria-label="任务详情"]')
        expect(details).to_contain_text('浏览器单角色邮件')
        expect(details).to_contain_text('待发 1')
        page.get_by_role('button',name='确认发放',exact=True).click()
        expect(page.get_by_role('dialog')).to_contain_text('490009735 × 1')
        page.get_by_role('dialog').get_by_role('button',name='取消',exact=True).last.click()
        expect(details).to_contain_text('待发 1')
        page.get_by_role('button',name='确认发放',exact=True).click()
        page.get_by_role('button',name='确认并发放',exact=True).click()
        expect(details).to_contain_text('成功 1')
        expect(details.locator('tbody')).to_contain_text('已投递')
        expect(details.locator('tbody')).to_contain_text('0010')
        page.screenshot(path=str(out/'mail-receipt.png'),full_page=True)
        page.locator('nav a[href="#mail"]').click()
        page.get_by_role('button',name='新建福利规则',exact=True).click()
        page.get_by_label('发放范围').select_option('character')
        page.get_by_label('邮件标题').fill('浏览器新手福利')
        page.get_by_label('物品 ID',exact=True).fill('490009735')
        page.get_by_label('物品数量',exact=True).fill('1')
        page.get_by_role('button',name='保存规则',exact=True).click()
        rule=page.locator('tbody tr').filter(has_text='浏览器新手福利')
        expect(rule).to_have_count(1)
        expect(rule).to_contain_text('每角色一次')
        # Re-submit the same draft: one persisted rule, including after reload.
        page.get_by_role('button',name='保存规则',exact=True).click()
