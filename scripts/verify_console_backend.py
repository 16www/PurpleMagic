        expect(dialog.get_by_role('tab',name='基本资料',exact=True)).to_have_attribute('aria-selected','true')
        before=len(calls)
        page.wait_for_timeout(200)
        assert not any('/inventory' in c['url'] or '/quests' in c['url'] or '/mailbox' in c['url'] for c in calls[before:])
        dialog.get_by_role('tab',name='背包与仓库',exact=True).click()
